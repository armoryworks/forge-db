using Forge.Db;
using Npgsql;
using Xunit;

namespace Forge.Db.Tests;

/// <summary>
/// Integration coverage of <c>data/0070-rebuild-ledger-balances.sql</c> against a real Postgres.
/// Skips silently unless <c>FORGE_DB_TEST_DSN</c> is set (a postgres:// URL whose user has CREATEDB). It
/// creates a uniquely-named throwaway DB holding only the columns the script reads, runs the script there
/// through <see cref="DataSeedRunner.Apply"/>, and drops the DB in a finally.
/// </summary>
public class LedgerBalanceRebuildDbTests
{
    private const string ScriptName = "0070-rebuild-ledger-balances.sql";

    private const string Tables = """
        CREATE TABLE acct_journal_entries (id bigint PRIMARY KEY, fiscal_period_id integer NOT NULL, status varchar(20) NOT NULL);
        CREATE TABLE acct_journal_lines (id bigint PRIMARY KEY, journal_entry_id bigint NOT NULL, book_id integer NOT NULL, gl_account_id integer NOT NULL, currency_id integer NOT NULL, debit numeric(18,4) NOT NULL, credit numeric(18,4) NOT NULL, functional_amount numeric(18,4) NOT NULL);
        CREATE TABLE acct_ledger_balances (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id integer NOT NULL, gl_account_id integer NOT NULL, fiscal_period_id integer NOT NULL, currency_id integer NOT NULL, debit_total numeric(18,4) NOT NULL, credit_total numeric(18,4) NOT NULL);
        CREATE UNIQUE INDEX ux_acct_ledger_balances_grain ON acct_ledger_balances (book_id, gl_account_id, fiscal_period_id, currency_id);
        """;

    private const string Journal = """
        INSERT INTO acct_journal_entries VALUES (1, 10, 'Reversed'), (2, 11, 'Posted'), (3, 10, 'Posted'), (4, 10, 'Draft'), (5, 10, 'PendingApproval');
        INSERT INTO acct_journal_lines VALUES
            (1, 1, 1, 100, 1, 50, 0, 50), (2, 1, 1, 400, 1, 0, 50, 50),
            (3, 2, 1, 100, 1, 0, 50, 50), (4, 2, 1, 400, 1, 50, 0, 50),
            (5, 3, 1, 100, 1, 20, 0, 18), (6, 3, 1, 400, 1, 0, 20, 18),
            (7, 4, 1, 100, 1, 999, 0, 999), (8, 4, 1, 400, 1, 0, 999, 999),
            (9, 5, 1, 300, 1, 7, 0, 7), (10, 5, 1, 400, 1, 0, 7, 7);
        """;

    private static string? Dsn => Environment.GetEnvironmentVariable("FORGE_DB_TEST_DSN");

    [Fact]
    public void Apply_RebuildsDriftedMissingAndOrphanBalances_FromPostedAndReversedLines()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        WithScratchDb(Journal + """
            INSERT INTO acct_ledger_balances (book_id, gl_account_id, fiscal_period_id, currency_id, debit_total, credit_total) VALUES
                (1, 100, 10, 1, 999, 0),
                (1, 100, 11, 1, 0, 50),
                (1, 300, 10, 1, 7, 0);
            """, scratch =>
        {
            Assert.Equal("68.0000/0.0000", Balance(scratch, 100, 10));
            Assert.Equal("0.0000/68.0000", Balance(scratch, 400, 10));
            Assert.Equal("0.0000/50.0000", Balance(scratch, 100, 11));
            Assert.Equal("50.0000/0.0000", Balance(scratch, 400, 11));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM acct_ledger_balances WHERE gl_account_id = 300"));
            Assert.Equal(4L, ScalarLong(scratch, "SELECT count(*) FROM acct_ledger_balances"));
        });
    }

    [Fact]
    public void Apply_LeavesCorrectBalancesAlone()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        WithScratchDb(Journal + """
            INSERT INTO acct_ledger_balances (id, book_id, gl_account_id, fiscal_period_id, currency_id, debit_total, credit_total) VALUES
                (71, 1, 100, 10, 1, 68, 0),
                (72, 1, 400, 10, 1, 0, 68),
                (73, 1, 100, 11, 1, 0, 50),
                (74, 1, 400, 11, 1, 50, 0);
            """, scratch =>
        {
            Assert.Equal(4L, ScalarLong(scratch, "SELECT count(*) FROM acct_ledger_balances WHERE id BETWEEN 71 AND 74"));
            Assert.Equal(4L, ScalarLong(scratch, "SELECT count(*) FROM acct_ledger_balances"));
            Assert.Equal("68.0000/0.0000", Balance(scratch, 100, 10));
        });
    }

    private static string Balance(string conn, int accountId, int periodId)
        => ScalarString(conn, $"SELECT debit_total || '/' || credit_total FROM acct_ledger_balances WHERE gl_account_id = {accountId} AND fiscal_period_id = {periodId}");

    private static void WithScratchDb(string rows, Action<string> assert)
    {
        var repo = RepoRoot();
        var baseConn = DbUrl.ToNpgsql(Dsn!);
        var admin = new NpgsqlConnectionStringBuilder(baseConn) { Database = "postgres" }.ConnectionString;
        var scratchDb = "forge_ledger_rebuild_" + DateTime.UtcNow.Ticks;
        var scratch = new NpgsqlConnectionStringBuilder(baseConn) { Database = scratchDb }.ConnectionString;

        Exec(admin, $"CREATE DATABASE \"{scratchDb}\"");
        var root = Path.Combine(Path.GetTempPath(), scratchDb);
        try
        {
            Exec(scratch, Tables);
            if (rows.Length > 0) Exec(scratch, rows);
            Directory.CreateDirectory(Path.Combine(root, "data"));
            File.Copy(Path.Combine(repo, "data", ScriptName), Path.Combine(root, "data", ScriptName));

            var first = DataSeedRunner.Apply(root, scratch, allowMutation: true);
            Assert.Equal(1, first.Applied);
            assert(scratch);

            Exec(scratch, File.ReadAllText(Path.Combine(repo, "data", ScriptName)));
            assert(scratch);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            Exec(admin, $"DROP DATABASE IF EXISTS \"{scratchDb}\" WITH (FORCE)");
            if (Directory.Exists(root)) Directory.Delete(root, recursive: true);
        }
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "data", ScriptName)))
            dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException($"data/{ScriptName} not found above the test output.");
    }

    private static void Exec(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        cmd.ExecuteNonQuery();
    }

    private static long ScalarLong(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToInt64(cmd.ExecuteScalar()!);
    }

    private static string ScalarString(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToString(cmd.ExecuteScalar()!)!;
    }
}
