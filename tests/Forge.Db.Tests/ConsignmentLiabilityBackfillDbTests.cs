using Forge.Db;
using Npgsql;
using Xunit;

namespace Forge.Db.Tests;

/// <summary>
/// Integration coverage of <c>data/0080-consignment-liability-account.sql</c> against a real Postgres.
/// Skips silently unless <c>FORGE_DB_TEST_DSN</c> is set (a postgres:// URL whose user has CREATEDB). It
/// creates a uniquely-named throwaway DB holding only the columns the script reads, runs the script there
/// through <see cref="DataSeedRunner.Apply"/>, and drops the DB in a finally.
/// </summary>
public class ConsignmentLiabilityBackfillDbTests
{
    private const string ScriptName = "0080-consignment-liability-account.sql";

    private static string? Dsn => Environment.GetEnvironmentVariable("FORGE_DB_TEST_DSN");

    [Fact]
    public void Apply_AddsTheAccountAndRuleOnlyToSeededBooksThatLackThem()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        var repo = RepoRoot();
        var baseConn = DbUrl.ToNpgsql(Dsn!);
        var admin = new NpgsqlConnectionStringBuilder(baseConn) { Database = "postgres" }.ConnectionString;
        var scratchDb = "forge_consignment_backfill_" + DateTime.UtcNow.Ticks;
        var scratch = new NpgsqlConnectionStringBuilder(baseConn) { Database = scratchDb }.ConnectionString;

        Exec(admin, $"CREATE DATABASE \"{scratchDb}\"");
        var root = Path.Combine(Path.GetTempPath(), scratchDb);
        try
        {
            Exec(scratch, """
                CREATE TABLE acct_books (id integer PRIMARY KEY);
                CREATE TABLE acct_gl_accounts (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, book_id integer NOT NULL,
                    account_number varchar(50) NOT NULL, name varchar(200) NOT NULL, account_type varchar(20) NOT NULL,
                    normal_balance varchar(10) NOT NULL, is_control_account boolean NOT NULL, is_postable boolean NOT NULL,
                    is_active boolean NOT NULL, UNIQUE (book_id, account_number));
                CREATE TABLE acct_account_determination_rules (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    book_id integer NOT NULL, key varchar(50) NOT NULL, gl_account_id integer NOT NULL);
                INSERT INTO acct_books VALUES (1), (2), (3);
                INSERT INTO acct_gl_accounts (id, book_id, account_number, name, account_type, normal_balance, is_control_account, is_postable, is_active)
                VALUES (100, 1, '21000', 'GRNI', 'Liability', 'Credit', false, true, true),
                       (200, 2, '21000', 'GRNI', 'Liability', 'Credit', false, true, true),
                       (201, 2, '21900', 'Vendor stock owed', 'Liability', 'Credit', false, true, true);
                SELECT setval(pg_get_serial_sequence('acct_gl_accounts', 'id'), 500);
                INSERT INTO acct_account_determination_rules (book_id, key, gl_account_id)
                VALUES (1, 'GRNI', 100), (2, 'GRNI', 200), (2, 'CONSIGNMENT_LIABILITY', 201);
                """);
            Directory.CreateDirectory(Path.Combine(root, "data"));
            File.Copy(Path.Combine(repo, "data", ScriptName), Path.Combine(root, "data", ScriptName));

            var first = DataSeedRunner.Apply(root, scratch, allowMutation: true);
            Assert.Equal(1, first.Applied);

            Assert.Equal(1L, ScalarLong(scratch,
                "SELECT count(*) FROM acct_account_determination_rules r JOIN acct_gl_accounts a ON a.id = r.gl_account_id " +
                "WHERE r.book_id = 1 AND r.key = 'CONSIGNMENT_LIABILITY' AND a.account_number = '21100'"));
            Assert.Equal(201L, ScalarLong(scratch,
                "SELECT gl_account_id FROM acct_account_determination_rules WHERE book_id = 2 AND key = 'CONSIGNMENT_LIABILITY'"));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM acct_gl_accounts WHERE book_id = 2 AND account_number = '21100'"));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM acct_gl_accounts WHERE book_id = 3"));

            Exec(scratch, File.ReadAllText(Path.Combine(repo, "data", ScriptName)));
            Assert.Equal(1L, ScalarLong(scratch, "SELECT count(*) FROM acct_gl_accounts WHERE account_number = '21100'"));
            Assert.Equal(2L, ScalarLong(scratch, "SELECT count(*) FROM acct_account_determination_rules WHERE key = 'CONSIGNMENT_LIABILITY'"));
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            Exec(admin, $"DROP DATABASE IF EXISTS \"{scratchDb}\" WITH (FORCE)");
            if (Directory.Exists(root)) Directory.Delete(root, recursive: true);
        }
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "data", ScriptName)))
            dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException($"data/{ScriptName} not found above the test output.");
    }

    private static void Exec(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        cmd.ExecuteNonQuery();
    }

    private static long ScalarLong(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToInt64(cmd.ExecuteScalar()!);
    }
}
