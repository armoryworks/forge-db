using Forge.Db;
using Npgsql;
using Xunit;

namespace Forge.Db.Tests;

/// <summary>
/// Integration coverage of <c>data/0060-payment-terms.sql</c> against a real Postgres.
/// Skips silently unless <c>FORGE_DB_TEST_DSN</c> is set (a postgres:// URL whose user has CREATEDB). It
/// creates a uniquely-named throwaway DB holding only the columns the script reads, runs the script there
/// through <see cref="DataSeedRunner.Apply"/>, and drops the DB in a finally.
/// </summary>
public class PaymentTermsBackfillDbTests
{
    private const string ScriptName = "0060-payment-terms.sql";

    private const string Tables = """
        CREATE TABLE payment_terms (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, code varchar(30) NOT NULL, name varchar(100) NOT NULL, net_days integer NOT NULL, discount_percent numeric(7,4) NOT NULL DEFAULT 0, discount_days integer NOT NULL DEFAULT 0, legacy_credit_terms integer, is_active boolean NOT NULL DEFAULT true, sort_order integer NOT NULL DEFAULT 0, is_system boolean NOT NULL DEFAULT false, created_at timestamptz NOT NULL, updated_at timestamptz NOT NULL, deleted_at timestamptz);
        CREATE UNIQUE INDEX ux_payment_terms_code ON payment_terms (code);
        CREATE TABLE customers (id integer PRIMARY KEY, default_credit_terms integer, payment_terms_id integer);
        CREATE TABLE vendors (id integer PRIMARY KEY, payment_terms varchar(200), payment_terms_id integer);
        CREATE TABLE sales_orders (id integer PRIMARY KEY, credit_terms integer, payment_terms_id integer);
        CREATE TABLE invoices (id integer PRIMARY KEY, credit_terms integer, payment_terms_id integer);
        CREATE TABLE vendor_bills (id integer PRIMARY KEY, credit_terms integer, payment_terms_id integer);
        """;

    private static string? Dsn => Environment.GetEnvironmentVariable("FORGE_DB_TEST_DSN");

    [Fact]
    public void Apply_SeedsTheSystemTerms_WithTheirLegacyValues()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        WithScratchDb(string.Empty, scratch =>
        {
            Assert.Equal(10L, ScalarLong(scratch, "SELECT count(*) FROM payment_terms WHERE is_system"));
            Assert.Equal(2L, ScalarLong(scratch, "SELECT legacy_credit_terms FROM payment_terms WHERE code = 'Net30'"));
            Assert.Equal(2m, ScalarDecimal(scratch, "SELECT discount_percent FROM payment_terms WHERE code = '2/10Net30'"));
            Assert.Equal(10L, ScalarLong(scratch, "SELECT discount_days FROM payment_terms WHERE code = '2/10Net30'"));
            Assert.Equal(30L, ScalarLong(scratch, "SELECT net_days FROM payment_terms WHERE code = '2/10Net30'"));
        });
    }

    [Fact]
    public void Apply_KeepsATermsRowTheTenantAlreadyHas()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        WithScratchDb("""
            INSERT INTO payment_terms (code, name, net_days, created_at, updated_at) VALUES ('Net30', 'Thirty days', 30, now(), now());
            """, scratch =>
        {
            Assert.Equal("Thirty days", ScalarString(scratch, "SELECT name FROM payment_terms WHERE code = 'Net30'"));
            Assert.Equal(1L, ScalarLong(scratch, "SELECT count(*) FROM payment_terms WHERE code = 'Net30'"));
        });
    }

    [Fact]
    public void Apply_MapsLegacyCreditTermsAndVendorText_ToTerms()
    {
        if (string.IsNullOrWhiteSpace(Dsn)) return;

        WithScratchDb("""
            INSERT INTO customers VALUES (1, 2, NULL), (2, NULL, NULL), (3, 5, NULL);
            INSERT INTO sales_orders VALUES (1, 0, NULL), (2, NULL, NULL);
            INSERT INTO invoices VALUES (1, 4, NULL);
            INSERT INTO vendor_bills VALUES (1, 1, NULL);
            INSERT INTO vendors VALUES (1, 'Net 30', NULL), (2, '2/10 Net 30', NULL), (3, 'net30', NULL), (4, 'Pay when you can', NULL), (5, NULL, NULL), (6, '  due on receipt ', NULL);
            """, scratch =>
        {
            Assert.Equal("Net30", ScalarString(scratch, "SELECT t.code FROM customers c JOIN payment_terms t ON t.id = c.payment_terms_id WHERE c.id = 1"));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM customers WHERE id = 2 AND payment_terms_id IS NOT NULL"));
            Assert.Equal("Net90", ScalarString(scratch, "SELECT t.code FROM customers c JOIN payment_terms t ON t.id = c.payment_terms_id WHERE c.id = 3"));
            Assert.Equal("DueOnReceipt", ScalarString(scratch, "SELECT t.code FROM sales_orders s JOIN payment_terms t ON t.id = s.payment_terms_id WHERE s.id = 1"));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM sales_orders WHERE id = 2 AND payment_terms_id IS NOT NULL"));
            Assert.Equal("Net60", ScalarString(scratch, "SELECT t.code FROM invoices i JOIN payment_terms t ON t.id = i.payment_terms_id WHERE i.id = 1"));
            Assert.Equal("Net15", ScalarString(scratch, "SELECT t.code FROM vendor_bills b JOIN payment_terms t ON t.id = b.payment_terms_id WHERE b.id = 1"));
            Assert.Equal("Net30", ScalarString(scratch, "SELECT t.code FROM vendors v JOIN payment_terms t ON t.id = v.payment_terms_id WHERE v.id = 1"));
            Assert.Equal("2/10Net30", ScalarString(scratch, "SELECT t.code FROM vendors v JOIN payment_terms t ON t.id = v.payment_terms_id WHERE v.id = 2"));
            Assert.Equal("Net30", ScalarString(scratch, "SELECT t.code FROM vendors v JOIN payment_terms t ON t.id = v.payment_terms_id WHERE v.id = 3"));
            Assert.Equal(0L, ScalarLong(scratch, "SELECT count(*) FROM vendors WHERE id IN (4, 5) AND payment_terms_id IS NOT NULL"));
            Assert.Equal("Pay when you can", ScalarString(scratch, "SELECT payment_terms FROM vendors WHERE id = 4"));
            Assert.Equal("DueOnReceipt", ScalarString(scratch, "SELECT t.code FROM vendors v JOIN payment_terms t ON t.id = v.payment_terms_id WHERE v.id = 6"));
        });
    }

    private static void WithScratchDb(string rows, Action<string> assert)
    {
        var repo = RepoRoot();
        var baseConn = DbUrl.ToNpgsql(Dsn!);
        var admin = new NpgsqlConnectionStringBuilder(baseConn) { Database = "postgres" }.ConnectionString;
        var scratchDb = "forge_payment_terms_" + DateTime.UtcNow.Ticks;
        var scratch = new NpgsqlConnectionStringBuilder(baseConn) { Database = scratchDb }.ConnectionString;

        Exec(admin, $"CREATE DATABASE \"{scratchDb}\"");
        var root = Path.Combine(Path.GetTempPath(), scratchDb);
        try
        {
            Exec(scratch, Tables);
            if (rows.Length > 0) Exec(scratch, rows);
            Directory.CreateDirectory(Path.Combine(root, "data"));
            File.Copy(Path.Combine(repo, "data", ScriptName), Path.Combine(root, "data", ScriptName));

            var first = DataSeedRunner.Apply(root, scratch, allowMutation: true);
            Assert.Equal(1, first.Applied);
            assert(scratch);

            Exec(scratch, File.ReadAllText(Path.Combine(repo, "data", ScriptName)));
            assert(scratch);
        }
        finally
        {
            NpgsqlConnection.ClearAllPools();
            Exec(admin, $"DROP DATABASE IF EXISTS \"{scratchDb}\" WITH (FORCE)");
            if (Directory.Exists(root)) Directory.Delete(root, recursive: true);
        }
    }

    private static string RepoRoot()
    {
        var dir = new DirectoryInfo(AppContext.BaseDirectory);
        while (dir is not null && !File.Exists(Path.Combine(dir.FullName, "data", ScriptName)))
            dir = dir.Parent;
        return dir?.FullName ?? throw new InvalidOperationException($"data/{ScriptName} not found above the test output.");
    }

    private static void Exec(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        cmd.ExecuteNonQuery();
    }

    private static long ScalarLong(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToInt64(cmd.ExecuteScalar()!);
    }

    private static decimal ScalarDecimal(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToDecimal(cmd.ExecuteScalar()!);
    }

    private static string ScalarString(string conn, string sql)
    {
        using var c = new NpgsqlConnection(conn);
        c.Open();
        using var cmd = new NpgsqlCommand(sql, c);
        return Convert.ToString(cmd.ExecuteScalar()!)!;
    }
}
