CREATE TABLE public.payment_runs (
    id integer NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    run_number character varying(20) NOT NULL,
    status integer DEFAULT 0 NOT NULL,
    payment_date timestamp with time zone NOT NULL,
    method character varying(20) NOT NULL,
    reference_number character varying(100),
    notes character varying(2000),
    apply_vendor_credits boolean DEFAULT true NOT NULL,
    created_by_user_id integer,
    started_at timestamp with time zone,
    completed_at timestamp with time zone,
    last_error character varying(2000),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

ALTER TABLE public.payment_runs ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.payment_runs_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.payment_runs
    ADD CONSTRAINT pk_payment_runs PRIMARY KEY (id);

ALTER TABLE ONLY public.payment_runs
    ADD CONSTRAINT ck_payment_runs_status CHECK (status = ANY (ARRAY[0, 1, 2, 3, 4]));
