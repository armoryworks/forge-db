CREATE TABLE public.customer_refunds (
    id integer NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    refund_number character varying(20) NOT NULL,
    customer_id integer NOT NULL,
    currency_id integer NOT NULL,
    fx_rate numeric(18,8) DEFAULT 1 NOT NULL,
    amount numeric(18,2) NOT NULL,
    method integer NOT NULL,
    refund_date timestamp with time zone NOT NULL,
    reference character varying(100),
    notes character varying(2000),
    credit_memo_id integer,
    payment_id integer,
    status integer DEFAULT 0 NOT NULL,
    voided_at timestamp with time zone,
    void_reason character varying(500),
    created_by_user_id integer,
    external_id character varying(100),
    external_ref character varying(100),
    provider character varying(50),
    last_synced_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

