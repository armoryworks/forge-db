CREATE TABLE public.vendor_returns (
    id integer NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    return_number character varying(20) NOT NULL,
    vendor_id integer NOT NULL,
    non_conformance_id integer,
    purchase_order_id integer,
    purchase_order_line_id integer,
    receiving_record_id integer,
    currency_id integer NOT NULL,
    fx_rate numeric(18,8) DEFAULT 1 NOT NULL,
    status integer DEFAULT 0 NOT NULL,
    ship_date timestamp with time zone,
    carrier character varying(100),
    tracking_number character varying(100),
    rma_number character varying(100),
    notes character varying(2000),
    shipped_by_user_id integer,
    created_by_user_id integer,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

