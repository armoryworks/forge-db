CREATE TABLE public.payment_run_items (
    id integer NOT NULL,
    payment_run_id integer NOT NULL,
    vendor_bill_id integer NOT NULL,
    vendor_id integer NOT NULL,
    currency_id integer NOT NULL,
    amount numeric(18,2) NOT NULL,
    discount_amount numeric(18,2),
    status integer DEFAULT 0 NOT NULL,
    vendor_payment_id integer,
    error_message character varying(2000),
    processed_at timestamp with time zone
);

ALTER TABLE public.payment_run_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.payment_run_items_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT pk_payment_run_items PRIMARY KEY (id);

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT ck_payment_run_items_status CHECK (status = ANY (ARRAY[0, 1, 2]));

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT ck_payment_run_items_amount CHECK (amount >= (0)::numeric);

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT fk_payment_run_items_payment_runs_payment_run_id FOREIGN KEY (payment_run_id) REFERENCES public.payment_runs(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT fk_payment_run_items_vendor_bills_vendor_bill_id FOREIGN KEY (vendor_bill_id) REFERENCES public.vendor_bills(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT fk_payment_run_items_vendors_vendor_id FOREIGN KEY (vendor_id) REFERENCES public.vendors(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT fk_payment_run_items_currencies_currency_id FOREIGN KEY (currency_id) REFERENCES public.currencies(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.payment_run_items
    ADD CONSTRAINT fk_payment_run_items_vendor_payments_vendor_payment_id FOREIGN KEY (vendor_payment_id) REFERENCES public.vendor_payments(id) ON DELETE SET NULL;
