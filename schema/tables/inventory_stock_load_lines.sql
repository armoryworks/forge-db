    ADD CONSTRAINT fk_inventory_stock_load_lines_part FOREIGN KEY (part_id) REFERENCES public.parts(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.inventory_stock_load_lines
    ADD CONSTRAINT fk_inventory_stock_load_lines_location FOREIGN KEY (storage_location_id) REFERENCES public.storage_locations(id) ON DELETE RESTRICT;

