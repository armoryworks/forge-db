CREATE TABLE public.inventory_stock_load_lines (
    id integer NOT NULL,
    stock_load_id integer NOT NULL,
    line_number integer NOT NULL,
    part_id integer NOT NULL,
    storage_location_id integer NOT NULL,
    lot_number character varying(100),
    expiration_date date,
    quantity numeric(18,4) NOT NULL,
    unit_cost numeric(18,4) NOT NULL,
    extended_value numeric(18,2) NOT NULL,
    bin_content_id integer,
    bin_movement_id integer
);

ALTER TABLE public.inventory_stock_load_lines ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.inventory_stock_load_lines_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.inventory_stock_load_lines
    ADD CONSTRAINT pk_inventory_stock_load_lines PRIMARY KEY (id);

ALTER TABLE ONLY public.inventory_stock_load_lines
    ADD CONSTRAINT ck_inventory_stock_load_lines_quantity CHECK (quantity > (0)::numeric);

ALTER TABLE ONLY public.inventory_stock_load_lines
    ADD CONSTRAINT ck_inventory_stock_load_lines_unit_cost CHECK (unit_cost >= (0)::numeric);

