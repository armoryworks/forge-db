CREATE TABLE public.coa_results (
    id integer NOT NULL,
    certificate_id integer NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL,
    characteristic character varying(300) NOT NULL,
    specification character varying(500),
    spec_min numeric(18,6),
    spec_max numeric(18,6),
    spec_target numeric(18,6),
    result character varying(200),
    unit character varying(30),
    method character varying(200),
    pass boolean NOT NULL,
    source_type character varying(20) NOT NULL,
    source_id integer
);

ALTER TABLE public.coa_results ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.coa_results_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.coa_results
    ADD CONSTRAINT pk_coa_results PRIMARY KEY (id);

ALTER TABLE ONLY public.coa_results
    ADD CONSTRAINT fk_coa_results_certificates_of_analysis_certificate_id FOREIGN KEY (certificate_id) REFERENCES public.certificates_of_analysis(id) ON DELETE CASCADE;
