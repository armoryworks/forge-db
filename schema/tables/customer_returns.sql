CREATE TABLE public.customer_returns (
    id integer NOT NULL,
    return_number character varying(50) NOT NULL,
    customer_id integer NOT NULL,
    original_job_id integer,
    sales_order_line_id integer,
    rework_job_id integer,
    reason character varying(1000) NOT NULL,
    notes character varying(2000),
    status integer NOT NULL,
    return_date timestamp with time zone NOT NULL,
    inspected_by_id integer,
    inspected_at timestamp with time zone,
    inspection_notes character varying(2000),
    channel_id integer,
    external_rma_id character varying(200),
    refund_amount numeric(18,2),
    quantity numeric(18,4),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text,
    invoice_id integer,
    invoice_line_id integer,
    disposition integer,
    quantity_restocked numeric(18,4),
    quantity_scrapped numeric(18,4),
    restock_location_id integer,
    restock_lot_number character varying(100),
    restock_bin_movement_id integer,
    credit_memo_id integer
);

