CREATE TABLE public.payment_terms (
    id integer NOT NULL,
    code character varying(30) NOT NULL,
    name character varying(100) NOT NULL,
    net_days integer NOT NULL,
    discount_percent numeric(7,4) DEFAULT 0 NOT NULL,
    discount_days integer DEFAULT 0 NOT NULL,
    legacy_credit_terms integer,
    is_active boolean DEFAULT true NOT NULL,
    sort_order integer DEFAULT 0 NOT NULL,
    is_system boolean DEFAULT false NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

ALTER TABLE public.payment_terms ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.payment_terms_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.payment_terms
    ADD CONSTRAINT pk_payment_terms PRIMARY KEY (id);

ALTER TABLE ONLY public.payment_terms
    ADD CONSTRAINT ck_payment_terms_days CHECK (net_days >= 0 AND discount_days >= 0 AND discount_percent >= 0 AND discount_percent < 100 AND (discount_percent = 0 OR discount_days < net_days));
