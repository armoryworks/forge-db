CREATE TABLE public.credit_memo_lines (
    id integer NOT NULL,
    credit_memo_id integer NOT NULL,
    line_number integer NOT NULL,
    line_type integer DEFAULT 0 NOT NULL,
    part_id integer,
    invoice_line_id integer,
    description character varying(500) NOT NULL,
    quantity numeric(18,4) NOT NULL,
    unit_price numeric(18,4) NOT NULL,
    tax_code character varying(10)
);

ALTER TABLE public.credit_memo_lines ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.credit_memo_lines_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.credit_memo_lines
    ADD CONSTRAINT pk_credit_memo_lines PRIMARY KEY (id);

ALTER TABLE ONLY public.credit_memo_lines
    ADD CONSTRAINT ck_credit_memo_lines_line_type CHECK (line_type = ANY (ARRAY[0, 1, 2, 3]));

ALTER TABLE ONLY public.credit_memo_lines
    ADD CONSTRAINT fk_credit_memo_lines_credit_memos_credit_memo_id FOREIGN KEY (credit_memo_id) REFERENCES public.credit_memos(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.credit_memo_lines
    ADD CONSTRAINT fk_credit_memo_lines_parts_part_id FOREIGN KEY (part_id) REFERENCES public.parts(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.credit_memo_lines
    ADD CONSTRAINT fk_credit_memo_lines_invoice_lines_invoice_line_id FOREIGN KEY (invoice_line_id) REFERENCES public.invoice_lines(id) ON DELETE RESTRICT;
