CREATE TABLE public.credit_memos (
    id integer NOT NULL,
    version bigint DEFAULT 1 NOT NULL,
    credit_memo_number character varying(20) NOT NULL,
    customer_id integer NOT NULL,
    currency_id integer NOT NULL,
    fx_rate numeric(18,8) DEFAULT 1 NOT NULL,
    invoice_id integer,
    customer_return_id integer,
    reason_type integer DEFAULT 0 NOT NULL,
    reason character varying(500) NOT NULL,
    status integer DEFAULT 0 NOT NULL,
    credit_date timestamp with time zone NOT NULL,
    tax_rate numeric(8,6) DEFAULT 0 NOT NULL,
    sales_tax_rate_id integer,
    notes character varying(2000),
    created_by_user_id integer,
    issued_by_user_id integer,
    issued_at timestamp with time zone,
    voided_at timestamp with time zone,
    void_reason character varying(500),
    external_id character varying(100),
    external_ref character varying(100),
    provider character varying(50),
    last_synced_at timestamp with time zone,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

