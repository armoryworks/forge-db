CREATE TABLE public.physical_inventories (
    id integer NOT NULL,
    inventory_number character varying(20) NOT NULL,
    description character varying(200),
    scope_location_id integer,
    status integer DEFAULT 0 NOT NULL,
    count_date date NOT NULL,
    blind_count boolean DEFAULT true NOT NULL,
    recount_tolerance_percent numeric(9,4) DEFAULT 0 NOT NULL,
    notes character varying(1000),
    frozen_at timestamp with time zone,
    frozen_by_user_id integer,
    posted_at timestamp with time zone,
    posted_by_user_id integer,
    cancelled_at timestamp with time zone,
    cancelled_by_user_id integer,
    total_variance_value numeric(18,2) DEFAULT 0 NOT NULL,
    created_by_user_id integer,
    version bigint DEFAULT 1 NOT NULL,
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

