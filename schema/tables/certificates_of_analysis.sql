CREATE TABLE public.certificates_of_analysis (
    id integer NOT NULL,
    certificate_number character varying(30) NOT NULL,
    lot_record_id integer NOT NULL,
    part_id integer NOT NULL,
    customer_id integer,
    shipment_id integer,
    status integer DEFAULT 0 NOT NULL,
    conforms boolean DEFAULT true NOT NULL,
    language character varying(10) DEFAULT 'en'::character varying NOT NULL,
    generated_at timestamp with time zone NOT NULL,
    generated_by_id integer,
    file_attachment_id integer,
    notes character varying(2000),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL,
    deleted_at timestamp with time zone,
    deleted_by text
);

ALTER TABLE public.certificates_of_analysis ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.certificates_of_analysis_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT pk_certificates_of_analysis PRIMARY KEY (id);

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT ck_certificates_of_analysis_status CHECK (status = ANY (ARRAY[0, 1]));

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT fk_certificates_of_analysis_lot_records_lot_record_id FOREIGN KEY (lot_record_id) REFERENCES public.lot_records(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT fk_certificates_of_analysis_parts_part_id FOREIGN KEY (part_id) REFERENCES public.parts(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT fk_certificates_of_analysis_customers_customer_id FOREIGN KEY (customer_id) REFERENCES public.customers(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT fk_certificates_of_analysis_shipments_shipment_id FOREIGN KEY (shipment_id) REFERENCES public.shipments(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.certificates_of_analysis
    ADD CONSTRAINT fk_certificates_of_analysis_file_attachments_file_attachment_id FOREIGN KEY (file_attachment_id) REFERENCES public.file_attachments(id) ON DELETE SET NULL;
