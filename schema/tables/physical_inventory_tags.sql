CREATE TABLE public.physical_inventory_tags (
    id integer NOT NULL,
    physical_inventory_id integer NOT NULL,
    tag_number integer NOT NULL,
    location_id integer NOT NULL,
    bin_content_id integer,
    part_id integer NOT NULL,
    lot_number character varying(100),
    serial_number character varying(100),
    frozen_quantity numeric(18,4) DEFAULT 0 NOT NULL,
    counted_quantity numeric(18,4),
    recount_quantity numeric(18,4),
    counted_by_user_id integer,
    counted_at timestamp with time zone,
    recounted_by_user_id integer,
    recounted_at timestamp with time zone,
    status integer DEFAULT 0 NOT NULL,
    unit_cost numeric(18,4),
    variance_value numeric(18,2),
    bin_movement_id integer,
    notes character varying(500),
    created_at timestamp with time zone NOT NULL,
    updated_at timestamp with time zone NOT NULL
);

ALTER TABLE public.physical_inventory_tags ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.physical_inventory_tags_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT pk_physical_inventory_tags PRIMARY KEY (id);

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT ck_physical_inventory_tags_status CHECK (status = ANY (ARRAY[0, 1, 2, 3, 4]));

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT ck_physical_inventory_tags_quantities CHECK (frozen_quantity >= (0)::numeric AND (counted_quantity IS NULL OR counted_quantity >= (0)::numeric) AND (recount_quantity IS NULL OR recount_quantity >= (0)::numeric));

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT fk_physical_inventory_tags_physical_inventory FOREIGN KEY (physical_inventory_id) REFERENCES public.physical_inventories(id) ON DELETE CASCADE;

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT fk_physical_inventory_tags_location FOREIGN KEY (location_id) REFERENCES public.storage_locations(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT fk_physical_inventory_tags_bin_content FOREIGN KEY (bin_content_id) REFERENCES public.bin_contents(id) ON DELETE SET NULL;

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT fk_physical_inventory_tags_part FOREIGN KEY (part_id) REFERENCES public.parts(id) ON DELETE RESTRICT;

ALTER TABLE ONLY public.physical_inventory_tags
    ADD CONSTRAINT fk_physical_inventory_tags_bin_movement FOREIGN KEY (bin_movement_id) REFERENCES public.bin_movements(id) ON DELETE SET NULL;
